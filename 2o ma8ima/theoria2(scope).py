#Εμβέλια scope
#Η εμβέλεια (scope) μιας μεταβλητής ή μιας συνάρτησης,
# ορίζει την περιοχή του κώδικα,
# στην οποία το όνομά της είναι αναγνωρίσιμο και μπορεί να χρησιμοποιηθεί.
#
#τοπική εμβέλια (local scope)
#1. Τοπική Εμβέλεια (Local Scope):
#• Αφορά μεταβλητές που δηλώνονται μέσα σε μια συνάρτηση ή ένα μπλοκ κώδικα (π.χ. μέσα σε μια if ή μια for).
#• Οι μεταβλητές αυτές «γεννιούνται» όταν ξεκινά η συνάρτηση και «πεθαίνουν» (διαγράφονται από τη μνήμη) όταν αυτή τελειώσει.
#• Δεν είναι προσβάσιμες από το υπόλοιπο πρόγραμμα
#
#Καθολική εμβέλια (global scope)
#1. 
#• Αφορά μεταβλητές που δηλώνονται έξω από οποιαδήποτε συνάρτηση,
# συνήθως στην αρχή του αρχείου κώδικα.
#• Είναι προσβάσιμες από οποιοδήποτε σημείο του προγράμματος
#  (και μέσα από τις συναρτήσεις).